// Agente HTTPS com as raízes públicas + os intermediários que o servidor da
// unidade não envia (certificadosConfiaveis). A verificação do certificado
// continua COMPLETA — só acrescentamos o elo que falta na cadeia.
export function agenteDaUnidade(unidade: SescUnidade): Agent | undefined {
  if (!unidade.certificadosConfiaveis?.length) return undefined
  return new Agent({ ca: [...rootCertificates, ...unidade.certificadosConfiaveis] })
}
