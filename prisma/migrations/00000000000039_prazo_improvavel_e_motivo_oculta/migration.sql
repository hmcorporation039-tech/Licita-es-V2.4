ALTER TABLE "tenders" ADD COLUMN IF NOT EXISTS "motivo_oculta" TEXT;

ALTER TABLE "tenders" ADD COLUMN IF NOT EXISTS "prazo_improvavel" BOOLEAN NOT NULL GENERATED ALWAYS AS (
  "encerramento_at" IS NOT NULL
  AND "modalidade" IN ('PREGAO_ELETRONICO', 'PREGAO_PRESENCIAL', 'CONCORRENCIA', 'DISPENSA_COM_DISPUTA', 'DISPENSA_SEM_DISPUTA', 'CONVITE', 'TOMADA_DE_PRECOS', 'CONCURSO', 'DIALOGO_COMPETITIVO')
  AND "encerramento_at" > COALESCE(GREATEST("publicado_at", "abertura_at"), "created_at") + INTERVAL '366 days'
) STORED;
